# ==========================================
# FORMATAR MOEDA
# ==========================================

def moeda(valor):

    return f"R$ {valor:,.2f}"


# ==========================================
# FORMATAR PERCENTUAL
# ==========================================

def percentual(valor):

    return f"{valor:.2f}%"


# ==========================================
# FORMATAR NÚMERO
# ==========================================

def numero(valor):

    return f"{valor:,}"